export function ensureIcon(button: HTMLElement, name: IconName): void {
  const mark = button.querySelector<SVGSVGElement>(":scope > .btn-icon");
  if (mark?.dataset.icon === name) return;
  const next = icon(name);
  if (mark) mark.replaceWith(next);
  else button.prepend(next);
}

export function icon(name: IconName): SVGSVGElement {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.5");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.classList.add("btn-icon");
  svg.dataset.icon = name;
  svg.innerHTML = PATHS[name];
  return svg;
}

/** Replace the button face without wiping the icon when the label changes. */
export function setButtonFace(button: HTMLElement, name: IconName, text?: string): void {
  let mark = button.querySelector<SVGSVGElement>(":scope > .btn-icon");
  if (!mark || mark.dataset.icon !== name) {
    const next = icon(name);
    if (mark) mark.replaceWith(next);
    else button.prepend(next);
    mark = next;
  }
  if (text === undefined) {
    for (const node of Array.from(button.childNodes)) {
      if (node !== mark) node.remove();
    }
    return;
  }
  let label = button.querySelector<HTMLElement>(":scope > .btn-label");
  if (!label) {
    label = document.createElement("span");
    label.className = "btn-label";
    button.append(label);
  }
  label.textContent = text;
  if (button.hasAttribute("aria-label")) button.setAttribute("aria-label", text);
  for (const node of Array.from(button.childNodes)) {
    if (node !== mark && node !== label) node.remove();
  }
}
