export type MessageKey = keyof typeof zh;

const STORAGE_KEY = "piano-tutor-lang";
const listeners = new Set<() => void>();

function detect(): Locale {
  try {
    const saved = globalThis.localStorage?.getItem?.(STORAGE_KEY);
    if (saved === "en" || saved === "zh-CN") return saved;
    const language = globalThis.navigator?.language ?? "zh";
    return language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
  } catch {
    return "zh-CN";
  }
}

let current: Locale = detect();

export function locale(): Locale {
  return current;
}

export function langCode(): "zh" | "en" {
  return current === "en" ? "en" : "zh";
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let text: string = current === "en" ? en[key] : zh[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function dictionaries(): { "zh-CN": typeof zh; en: typeof en } {
  return { "zh-CN": zh, en };
}

export function onLocale(listener: () => void): void {
  listeners.add(listener);
}

export function setLocale(next: Locale): void {
  current = next;
  try {
    globalThis.localStorage?.setItem?.(STORAGE_KEY, next);
  } catch {
    // Storage can be unavailable in private or non-browser runs.
  }
  document.documentElement.lang = next === "en" ? "en" : "zh-CN";
  document.title = t("appTitle");
  applyI18n();
  for (const listener of listeners) listener();
}

export function applyI18n(): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = current === "en" ? "en" : "zh-CN";
  document.title = t("appTitle");
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n as MessageKey;
    if (!key || !(key in zh)) return;
    const text = t(key);
    const label = node.querySelector(":scope > .btn-label");
    if (label) label.textContent = text;
    else if (node.querySelector(":scope > .btn-icon")) return;
    else node.textContent = text;
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((node) => {
    const key = node.dataset.i18nTitle as MessageKey;
    if (key && key in zh) node.title = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((node) => {
    const key = node.dataset.i18nAria as MessageKey;
    if (key && key in zh) node.setAttribute("aria-label", t(key));
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-tip]").forEach((node) => {
    const key = node.dataset.i18nTip as MessageKey;
    if (key && key in zh) node.setAttribute("data-tip", t(key));
  });
  document.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder as MessageKey;
    if (key && key in zh) node.placeholder = t(key);
  });
}

export function bootLocale(): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = current === "en" ? "en" : "zh-CN";
  document.title = t("appTitle");
  applyI18n();
}
